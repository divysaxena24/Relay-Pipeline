
import random
import time


class StandInError(Exception):
    """Base exception for simulated model-service errors."""


class StandInRateLimitError(StandInError):
    """Simulates an API rate-limit response."""


class StandInModel:
    def __init__(
        self,
        latency_ms: int = 573,
        failure_rate: float = 0.0,
        refusal_rate: float = 0.0,
        rate_limit_every: int = 0
    ):
        if latency_ms < 0:
            raise ValueError("latency_ms cannot be negative.")

        if not 0 <= failure_rate <= 1:
            raise ValueError("failure_rate must be between 0 and 1.")

        if not 0 <= refusal_rate <= 1:
            raise ValueError("refusal_rate must be between 0 and 1.")

        if rate_limit_every < 0:
            raise ValueError("rate_limit_every cannot be negative.")

        self.latency_ms = latency_ms
        self.failure_rate = failure_rate
        self.refusal_rate = refusal_rate
        self.rate_limit_every = rate_limit_every
        self.request_count = 0

    def _simulate_request(self):
        """Simulate one model-service request."""
        self.request_count += 1

        if (
            self.rate_limit_every > 0
            and self.request_count % self.rate_limit_every == 0
        ):
            raise StandInRateLimitError(
                "429: Simulated rate limit exceeded."
            )

        if random.random() < self.failure_rate:
            raise StandInError(
                "503: Simulated model service failure."
            )

        start = time.perf_counter()

        time.sleep(self.latency_ms / 1000)

        return start

    def check_evidence(self, question: str, context: str):
        start = self._simulate_request()

        question_terms = set(question.lower().split())
        context_terms = set(context.lower().split())

        overlap = question_terms & context_terms
        sufficient = len(overlap) >= 2 and bool(context.strip())

        latency = (time.perf_counter() - start) * 1000

        return {
            "sufficient": sufficient,
            "decision": (
                "SUFFICIENT" if sufficient else "INSUFFICIENT"
            ),
            "request_id": f"standin-{self.request_count}",
            "tokens_in": len(question.split()) + len(context.split()),
            "tokens_out": 1,
            "latency_ms": round(latency, 2)
        }

    def generate(self, question: str, context: str = ""):
        start = self._simulate_request()

        if random.random() < self.refusal_rate:
            answer = (
                "I cannot answer this reliably using the "
                "available research papers."
            )
        else:
            answer = (
                "This is a simulated stand-in response. "
                "The actual answer would be generated by the "
                "hosted language model. [S1]"
            )

        latency = (time.perf_counter() - start) * 1000

        return {
            "answer": answer,
            "model": "relay-standin",
            "latency_ms": round(latency, 2),
            "tokens_in": len(question.split()) + len(context.split()),
            "tokens_out": len(answer.split()),
            "total_tokens": (
                len(question.split())
                + len(context.split())
                + len(answer.split())
            ),
            "finish_reason": "stop",
            "request_id": f"standin-{self.request_count}"
        }


    def generate_stream(self, question: str, context: str = ""):
        self._simulate_request()

        if random.random() < self.refusal_rate:
            answer = (
                "I cannot answer this reliably using the "
                "available research papers."
            )
        else:
            answer = (
                "The Transformer uses attention mechanisms "
                "to process relationships between tokens."
            )

        # Simulate streaming by yielding small pieces.
        words = answer.split()

        for word in words:
            time.sleep(0.05)
            yield word + " "
